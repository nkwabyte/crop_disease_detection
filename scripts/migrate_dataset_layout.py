#!/usr/bin/env python3
"""
migrate_dataset_layout.py — move dataset/ to data/detector/, grouped by crop.

Before                                  After
------                                  -----
dataset/train/<uuid>.jpg                data/detector/train/Tomato/<uuid>.jpg
dataset/final_train_labels.csv          data/detector/final_train_labels.csv
dataset/classifier_*.csv                (removed — regenerated into data/yolo/)

Why `detector` and not `classifier`: these images are what the Faster R-CNN, ViT
and Swin detectors train on, via final_*_labels.csv. The classifier trains on
data/yolo/ — its classifier_*.csv rows point there — so naming this folder after
the classifier would label it as the one model that does not use it.

Grouping by crop is lossless here: every image carries exactly one crop (checked
below — the CSVs have one row per image and no image mixes crops).

The CSVs' img_path column is rewritten to the new location and normalised to
forward slashes (it previously used Windows-style backslashes).

Idempotent and resumable: an image already at its destination is skipped, so a
re-run after an interruption completes the job rather than failing.

Usage
-----
  python scripts/migrate_dataset_layout.py --dry-run     # report, change nothing
  python scripts/migrate_dataset_layout.py               # perform the migration
"""

from __future__ import annotations

import argparse
import csv
import shutil
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
SRC = PROJECT_ROOT / "dataset"
DST = PROJECT_ROOT / "data" / "detector"

SPLITS = [("train", "final_train_labels.csv"),
          ("validate", "final_validate_labels.csv"),
          ("test", "final_test_labels.csv")]
# Regenerated by src/classifier/generate_classifier_csv.py, and they reference
# data/yolo/ rather than these images, so they do not belong here.
DROP = ["classifier_train.csv", "classifier_valid.csv", "classifier_test.csv"]
KEEP_ASIS = ["label_map.json", "label_map.pbtxt"]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true", help="report only")
    args = ap.parse_args()

    if not SRC.exists() and DST.exists():
        print(f"  Already migrated: {SRC} is gone and {DST} exists.")
        return 0
    if not SRC.exists():
        print(f"  x nothing to migrate: {SRC} not found")
        return 1

    plan: list[tuple[Path, Path]] = []
    csv_out: dict[str, tuple[list[str], list[dict]]] = {}
    problems: list[str] = []

    for split, csv_name in SPLITS:
        csv_path = SRC / csv_name
        if not csv_path.exists():
            problems.append(f"missing {csv_path}")
            continue
        with csv_path.open(newline="") as fh:
            rdr = csv.DictReader(fh)
            fields, rows = list(rdr.fieldnames or []), list(rdr)

        # One row per image and one crop per image is what makes the grouping safe.
        by_img: dict[str, set] = {}
        for r in rows:
            by_img.setdefault(r["fname"], set()).add(r["crop"])
        multi = [k for k, v in by_img.items() if len(v) > 1]
        if multi:
            problems.append(f"{split}: {len(multi)} images span multiple crops "
                            f"— grouping by crop would be ambiguous")

        for r in rows:
            crop, fname = r["crop"], r["fname"]
            src_f = SRC / split / fname
            dst_f = DST / split / crop / fname
            rel = f"data/detector/{split}/{crop}/{fname}"
            r["img_path"] = rel                      # normalised, forward slashes
            if src_f.exists():
                plan.append((src_f, dst_f))
            elif not dst_f.exists():
                problems.append(f"missing image: {src_f}")
        csv_out[csv_name] = (fields, rows)
        print(f"  {split:9} {len(rows):6,} rows  ->  "
              f"{len({r['crop'] for r in rows})} crop folders")

    if problems:
        print("\n  PROBLEMS — nothing was changed:")
        for p in problems[:20]:
            print(f"    x {p}")
        if len(problems) > 20:
            print(f"    ... and {len(problems) - 20} more")
        return 1

    print(f"\n  {len(plan):,} images to move")
    if args.dry_run:
        for s, d in plan[:3]:
            print(f"    {s.relative_to(PROJECT_ROOT)}  ->  {d.relative_to(PROJECT_ROOT)}")
        print("  (dry run — nothing changed)")
        return 0

    for split, _ in SPLITS:
        for crop in ("Corn", "Pepper", "Tomato"):
            (DST / split / crop).mkdir(parents=True, exist_ok=True)

    moved = skipped = 0
    for src_f, dst_f in plan:
        if dst_f.exists():
            skipped += 1
            continue
        shutil.move(str(src_f), str(dst_f))
        moved += 1
        if moved % 10000 == 0:
            print(f"    moved {moved:,}/{len(plan):,}")
    print(f"  moved {moved:,}, already in place {skipped:,}")

    for csv_name, (fields, rows) in csv_out.items():
        out = DST / csv_name
        with out.open("w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=fields)
            w.writeheader()
            w.writerows(rows)
        print(f"  wrote {out.relative_to(PROJECT_ROOT)}")

    for name in KEEP_ASIS:
        if (SRC / name).exists():
            shutil.move(str(SRC / name), str(DST / name))
            print(f"  moved {name}")
    for name in DROP:
        if (SRC / name).exists():
            (SRC / name).unlink()
            print(f"  removed {name}  (regenerated into data/yolo/)")

    # Whatever is left behind is unexpected — report it instead of deleting blind.
    leftovers = [p for p in SRC.rglob("*") if p.is_file() and p.name != ".DS_Store"]
    if leftovers:
        print(f"\n  ! {len(leftovers)} unexpected file(s) left in {SRC}:")
        for p in leftovers[:10]:
            print(f"      {p.relative_to(PROJECT_ROOT)}")
        print("    Left in place — remove dataset/ by hand once you have checked them.")
    else:
        for p in sorted(SRC.rglob("*"), reverse=True):
            if p.is_file():
                p.unlink()
            else:
                p.rmdir()
        SRC.rmdir()
        print(f"  removed empty {SRC.relative_to(PROJECT_ROOT)}/")

    return 0


if __name__ == "__main__":
    sys.exit(main())
